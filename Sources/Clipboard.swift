import AppKit
import Foundation

/// Clipboard synchronization between this Mac and the PC.
///
/// Copy on one machine, paste on the other. Plain text, rich text, HTML and
/// images; anything else is left alone.
///
/// macOS gives no notification when the pasteboard changes, so this polls
/// `changeCount` — that is not a shortcut, it is the only mechanism AppKit
/// offers. The interval is a compromise nobody escapes: too slow and a copy has
/// not arrived by the time the user reaches the other keyboard, too fast and it
/// wakes constantly for nothing.
///
/// The conventions for WHAT to skip are borrowed from Maccy (MIT), which is
/// where the important one is documented: password managers mark their copies
/// with `org.nspasteboard.ConcealedType` precisely so that clipboard tools do
/// not persist or forward them. Sending those across a network to another
/// machine is exactly what that marker exists to prevent, and it is not
/// something you would think to check unless you had seen it.
final class ClipboardBridge {

    /// Wired to the KVM transport.
    var send: ((String) -> Void)?

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount

    /// Set when applying a payload that arrived FROM the PC, so the change it
    /// causes is not immediately sent back as though the user had copied it.
    /// Without this the two machines volley one copy between them forever.
    private var suppressUntilChangeCount = -1

    /// The clipboard has its own SSH channel now, so this is no longer about
    /// the pointer: a large paste cannot sit in front of pointer events any
    /// more. What remains is memory — the payload is held whole, and base64
    /// inflates it by a third at each end — so the cap is set where a copy
    /// stops being a copy and starts being a file transfer.
    private static let maximumPayload = 32 * 1_048_576

    /// Something the user should be told about, rather than only the log.
    var onNotice: ((String) -> Void)?

    /// Types that mean "do not persist or forward this".
    ///
    /// Concealed is the one that matters: it is how a password manager says so.
    private static let refusedTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    // MARK: Lifecycle

    func start(interval: TimeInterval = 0.5) {
        stop()
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            self?.poll()
        }
        // .common so it keeps running while a menu is open, which is exactly
        // when someone is likely to be mid-copy.
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        KVMLog.write("clipboard: watching (every \(interval)s)")
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    // MARK: Mac -> PC

    private func poll() {
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        if count == suppressUntilChangeCount { return }        // our own paste

        let types = pasteboard.types ?? []
        for refused in ClipboardBridge.refusedTypes where types.contains(refused) {
            KVMLog.write("clipboard: skipped a \(refused.rawValue) item")
            return
        }

        // Richest first, so formatting survives where the far side can take it.
        if let png = pasteboard.data(forType: .png) {
            emit("png", png)
        } else if let tiff = pasteboard.data(forType: .tiff),
                  let png = NSBitmapImageRep(data: tiff)?
                    .representation(using: .png, properties: [:]) {
            emit("png", png)
        } else if let rtf = pasteboard.data(forType: .rtf) {
            emit("rtf", rtf)
        // Deliberately no .html branch. Windows wants CF_HTML — a header
        // carrying byte offsets into the markup — and raw html pasted as text
        // would arrive as visible tags. Browsers are precisely where html shows
        // up, and they also offer rtf or plain text, so falling through costs
        // formatting in some cases and never produces garbage.
        } else if let text = pasteboard.string(forType: .string) {
            emit("text", Data(text.utf8))
        }
    }

    private func emit(_ format: String, _ data: Data) {
        guard !data.isEmpty else { return }
        guard data.count <= ClipboardBridge.maximumPayload else {
            // Say so. Dropped in silence, this looked like the clipboard simply
            // not working: copy here, walk over, paste nothing, no reason given.
            let megabytes = Double(data.count) / 1_048_576
            let note = String(format: "Clipboard item is %.1f MB — too large to send.", megabytes)
            KVMLog.write("clipboard: " + note)
            onNotice?(note)
            return
        }
        send?("C \(format) \(data.base64EncodedString())")
        KVMLog.write("clipboard: sent \(format), \(data.count) bytes")
    }

    // MARK: PC -> Mac

    /// Apply a payload that arrived from the PC.
    func apply(format: String, base64: String) {
        guard let data = Data(base64Encoded: base64), !data.isEmpty else {
            KVMLog.write("clipboard: received an undecodable \(format) payload")
            return
        }
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        switch format {
        case "text":
            pasteboard.setString(String(decoding: data, as: UTF8.self), forType: .string)
        case "rtf":
            pasteboard.setData(data, forType: .rtf)
        case "html":
            pasteboard.setData(data, forType: .html)
        case "png":
            pasteboard.setData(data, forType: .png)
        default:
            KVMLog.write("clipboard: ignoring unknown format \(format)")
            return
        }

        // Remember the change we just caused so poll() does not read it back
        // out and return it to the PC.
        suppressUntilChangeCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount
        KVMLog.write("clipboard: received \(format), \(data.count) bytes")
    }
}
